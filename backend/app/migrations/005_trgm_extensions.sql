-- 005_trgm_extensions.sql — §14 측정을 재현하기 위해 남겨 두는 문자열 유사도 확장
--
-- 애초에 m7의 broader 방향 판정이 비대칭 word_similarity()에 의존해 관계 생성보다 먼저
-- 설치했다. 그 판정은 §14에서 기각됐고(정답쌍에서도 방향 차가 벌어지지 않았다) 008이
-- broader를 제거했으므로, **현재 이 확장을 쓰는 애플리케이션 코드는 없다.**
--
-- ⚠️ 이 파일이 적어 두었던 회수 조건("m9가 잘리면 회수 대상")은 **발동했다** — m9가
-- 키워드 + 벡터 RRF를 실측 후 미채택했다(#12, ADR-016, §14). 그럼에도 **회수하지
-- 않는다.** ①이미 적용된 확장을 되돌리려면 DROP EXTENSION 마이그레이션을 새로 더해야
-- 해서 스키마 이력만 늘어난다 ②scripts/measure_relations.py가 word_similarity로 §14의
-- 방향 차·동점 분포를 재현하는데, 확장을 지우면 그 측정을 다시 못 돌린다 — 라이선스
-- 만료(2026-09-10) 이후에는 실 VM 재현 자체가 불가능하다 ③확장 하나의 비용은 사실상 0이다.
--
-- 즉 남는 근거는 **재현 가능성 하나**이며, 「쓰는 코드가 없으니 지워도 된다」는 판단의
-- 근거가 되지 않는다. 지우려면 위 ②를 먼저 해결해야 한다. pg_trgm 1.6은 로컬 pgvector
-- 컨테이너와 실 OpenSQL VM 양쪽에서 확인됐다 (OPENSQL_RESEARCH.md §14, ADR-026).
--
-- 적용 여부와 멱등성은 schema_migrations가 담당하므로 IF NOT EXISTS를 쓰지 않는다
-- (ADR-005). 확장이 없는 환경을 조용히 통과시키면 관계 판정이 뒤늦게 실패한다.

CREATE EXTENSION pg_trgm;
